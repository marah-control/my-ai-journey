# برنامج بسيط: نظام مراقبة درجة الحرارة

print("--- نظام مراقبة درجة الحرارة ---")

# قراءة درجة الحرارة من المستخدم
temp_input = input("أدخلي درجة الحرارة الحالية: ")

# تحويل النص المدخل إلى رقم عشري
temp = float(temp_input)

print(f"\nدرجة الحرارة المدخلة: {temp} °C")

# التحقق من الحالة (منطق التحكم)
if temp > 80:
    print("⚠️ تحذير: درجة الحرارة مرتفعة جداً! يجب إيقاف النظام.")
elif temp < 10:
    print("⚠️ تحذير: درجة الحرارة منخفضة جداً! يجب تشغيل التدفئة.")
else:
    print("✅ درجة الحرارة طبيعية. النظام يعمل بشكل سليم.")